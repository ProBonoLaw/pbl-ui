'use client';
import { CaseForm } from '@/components/cases/CaseForm';
import ModalDialog from '@/components/ModalDialog';
import PageTemplate from '@/components/PageTemplate';
import { useAccountAccess } from '@/hooks/useAccountAccess';
import { useAccountCases } from '@/hooks/useAccountCases';
import { CaseMap, OriginalCaseRecordRequest } from '@/lib/types';
import { useEffect, useState } from 'react';
import { useRouter } from 'next/navigation';

const CASE_SUBMISSION_FAILURE_MESSAGE =
  "Your request couldn't be fulfilled at this time. Please try again later.";

export default function Page() {
  const { createCase } = useAccountCases({ enabled: false });
  const { access, loading: loadingAccess, error: accessError } =
    useAccountAccess();
  const [pendingSubmission, setPendingSubmission] = useState<{
    caseData: CaseMap;
    isAttorney: boolean;
  } | null>(null);
  const [seekConfirmation, setSeekConfirmation] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [showSubmittedNotice, setShowSubmittedNotice] = useState(false);
  const [isCheckingAccess, setIsCheckingAccess] = useState(true);
  const [accessDeniedMessage, setAccessDeniedMessage] = useState<string | null>(
    null,
  );
  const redirect = useRouter();

  useEffect(() => {
    if (loadingAccess) {
      setIsCheckingAccess(true);
      return;
    }

    setIsCheckingAccess(false);

    if (accessError || !access) {
      setAccessDeniedMessage('You are not allowed to create a new case right now.');
      return;
    }

    if (access.agreedToTerms === false) {
      setAccessDeniedMessage(
        'Please contact your service administrator to complete the onboarding process. Until then, you cannot create a new case.',
      );
      return;
    }

    if (access.isActive === false) {
      setAccessDeniedMessage(
        'Your account is inactive. Please contact your service administrator for assistance.',
      );
      return;
    }

    setAccessDeniedMessage(null);
  }, [access, accessError, loadingAccess]);

  function queueCaseSubmission(caseData: CaseMap, isAttorney: boolean) {
    setPendingSubmission({ caseData, isAttorney });
    setSeekConfirmation(true);
  }

  async function submitCaseChanges() {
    if (!pendingSubmission) {
      return;
    }

    try {
      setIsSubmitting(true);
      const payload = {
        ...pendingSubmission.caseData.record,
        isAttorney: pendingSubmission.isAttorney,
        billingCode: pendingSubmission.caseData.billingCode,
      } as OriginalCaseRecordRequest;
      payload.accountId = undefined;
      payload.id = undefined;

      const result = await createCase(payload);
      if (!result.ok) {
        throw new Error(result.error);
      }

      setError(null);
      setSeekConfirmation(false);
      setPendingSubmission(null);
      setShowSubmittedNotice(true);
    } catch (e: unknown) {
      setError(CASE_SUBMISSION_FAILURE_MESSAGE);
      setSeekConfirmation(false);
      setPendingSubmission(null);
    } finally {
      setIsSubmitting(false);
    }
  }

  return (
    <>
      {seekConfirmation && (
        <ModalDialog
          title="Confirm Case Ownership"
          cancelText="Cancel"
          submitText={isSubmitting ? 'Submitting...' : 'Proceed'}
          opened={seekConfirmation}
          onApproved={submitCaseChanges}
          onCanceled={() => {
            setSeekConfirmation(false);
            setPendingSubmission(null);
            redirect.push('/cases');
          }}>
          <>
            <span>
              You are assuming ownership of this case and it will be billed to
              you.
            </span>
            <br />
            <br />
            {pendingSubmission?.isAttorney ? (
              <span>
                While responses are based on the data provided, they can still
                be prone to errors due to ambiguity, incompleteness, or other
                factors. Please review all content before submitting anything to
                the court. Would you like to proceed?
              </span>
            ) : (
              <span>
                ProBono Law is not an AI lawyer and does not provide services
                that replace or substitute for an attorney. Any content
                generated by ProBono Law should be reviewed by a licensed
                attorney to ensure accuracy and compliance with all local,
                state, and federal laws. Would you like to proceed?
              </span>
            )}
          </>
        </ModalDialog>
      )}
      {error && (
        <ModalDialog
          title="Request Failed"
          onApproved={() => setError(null)}
          submitText="OK"
          opened={!!error}>
          {error}
        </ModalDialog>
      )}
      {showSubmittedNotice && (
        <ModalDialog
          title="Case Submitted"
          opened={showSubmittedNotice}
          submitText="OK"
          cancelText={null}
          onApproved={() => {
            setShowSubmittedNotice(false);
            redirect.push('/cases');
          }}>
          Your case was submitted. Your case repository will be ready in a few
          minutes.
        </ModalDialog>
      )}
      {accessDeniedMessage && (
        <ModalDialog
          title="Access Restricted"
          opened={true}
          submitText="OK"
          cancelText={null}
          onApproved={() => {
            setAccessDeniedMessage(null);
            redirect.push('/');
          }}>
          {accessDeniedMessage}
        </ModalDialog>
      )}
      <PageTemplate title="Create New Case" isLoading={isCheckingAccess}>
        {!isCheckingAccess && !accessDeniedMessage && (
          <CaseForm
            onSubmit={queueCaseSubmission}
            isEditable={true}
            showBillingCode={true}
          />
        )}
      </PageTemplate>
    </>
  );
}
